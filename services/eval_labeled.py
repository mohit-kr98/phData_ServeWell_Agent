"""
Evaluate the agent's routing decisions against the official ground truth
provided with the challenge (tickets/train_index.csv's escalation_flag
column), and its retrieval quality against labels/train_labels.json.

IMPORTANT provenance note: train_index.csv (escalation_flag) is the official
data provided as part of the phData challenge. labels/train_labels.json
(correct_routing, relevant_kb_docs, etc.) was generated by an LLM as a
labeling aid, not verified/official ground truth -- the two disagree on
escalation for ~48% of tickets. So:

  - routing_accuracy is measured against escalation_flag (official): did the
    Triage Agent's L2_ESCALATION-or-not decision match the flag?
  - retrieval hit_rate / recall@k still uses train_labels.json's
    relevant_kb_docs, since no official retrieval ground truth exists --
    treat this metric as directional, not verified.

Calls the already-running api_service (POST /triage, POST /resolve) so it
exercises the real orchestration + retrieval path, not a mocked one.
"""
import argparse
import datetime
import json
import re
import sys
from pathlib import Path

import pandas as pd
import requests

# Allow `python3 services/eval_labeled.py` as well as `-m` / package imports
sys.path.insert(0, str(Path(__file__).parent.parent))

TRAIN_INDEX_CSV = Path("tickets/train_index.csv")
LABELS_PATH = Path("labels/train_labels.json")
TICKETS_DIR = Path("tickets/train")
API_URL = "http://localhost:8000"
SOURCE_RE = re.compile(r"--- Document Source: (.+?) ---")


def basename(doc_path: str) -> str:
    return doc_path.split("/")[-1]


def extract_retrieved_sources(trace: list) -> list[str]:
    sources = []
    for step in trace:
        if step.get("type") == "tool_result":
            sources.extend(SOURCE_RE.findall(step.get("result", "")))
    # de-dupe, preserve order
    seen = set()
    ordered = []
    for s in sources:
        if s not in seen:
            seen.add(s)
            ordered.append(s)
    return ordered


def strip_escalation_flag(ticket_json: str) -> str:
    """Remove the ITSM escalation_flag from the ticket before sending it.

    escalation_flag IS the routing ground truth and it ships inside the ticket,
    so honoring it (correct ITSM behavior) trivially scores ~100%. Stripping it
    measures the agent's *independent* triage judgment on tickets that carry no
    upstream routing instruction -- the harder and more informative number.
    Baseline for context: always-predict-L1 scores 74.2% on this set.
    """
    try:
        t = json.loads(ticket_json)
        t.pop("escalation_flag", None)
        return json.dumps(t)
    except Exception:
        return ticket_json


def evaluate(limit: int = 0, sleep_between: float = 0.0, strip_flag: bool = False):
    index_df = pd.read_csv(TRAIN_INDEX_CSV)
    if limit > 0:
        index_df = index_df.head(limit)

    # Retrieval ground truth (relevant_kb_docs) is only available from the
    # LLM-generated labels -- used for retrieval eval only, never routing.
    labels_by_id = {x["ticket_id"]: x for x in json.loads(LABELS_PATH.read_text())}

    routing_correct = 0
    routing_total = 0
    retrieval_hits = 0
    retrieval_recalls = []
    retrieval_total = 0
    errors = 0
    rows = []

    for _, index_row in index_df.iterrows():
        ticket_id = index_row["ticket_id"]
        ticket_file = TICKETS_DIR / f"{ticket_id}.json"
        if not ticket_file.exists():
            continue
        ticket_json = ticket_file.read_text()
        triage_input = strip_escalation_flag(ticket_json) if strip_flag else ticket_json
        expected_escalate = bool(index_row["escalation_flag"])
        relevant_docs = {basename(d) for d in labels_by_id.get(ticket_id, {}).get("relevant_kb_docs", [])}

        row = {"ticket_id": ticket_id, "expected_escalate": expected_escalate}
        try:
            triage_res = requests.post(f"{API_URL}/triage", json={"ticket_json": triage_input}, timeout=300).json()
            actual_routing = triage_res.get("routing", "ERROR").strip().lower()
            actual_escalate = actual_routing == "l2_escalation"
            routing_total += 1
            row["actual_routing"] = actual_routing
            row["routing_correct"] = actual_escalate == expected_escalate
            if row["routing_correct"]:
                routing_correct += 1

            if actual_routing == "l1_guided":
                resolve_res = requests.post(
                    f"{API_URL}/resolve", json={"ticket_json": ticket_json}, timeout=600
                ).json()
                trace = resolve_res.get("trace", [])
                retrieved = extract_retrieved_sources(trace)
                row["retrieved_docs"] = retrieved

                if relevant_docs:
                    retrieval_total += 1
                    hit = bool(relevant_docs & set(retrieved))
                    recall = len(relevant_docs & set(retrieved)) / len(relevant_docs)
                    row["retrieval_hit"] = hit
                    row["retrieval_recall"] = recall
                    retrieval_hits += int(hit)
                    retrieval_recalls.append(recall)

        except Exception as e:
            errors += 1
            row["error"] = str(e)

        rows.append(row)
        if sleep_between:
            import time

            time.sleep(sleep_between)

    metrics = {
        "total_tickets": len(index_df),
        "routing_mode": "reasoning_only (escalation_flag withheld from agent)" if strip_flag
                        else "flag_honored (agent sees the ITSM escalation_flag, as in production)",
        "routing_ground_truth": "tickets/train_index.csv:escalation_flag (official)",
        "retrieval_ground_truth": "labels/train_labels.json:relevant_kb_docs (LLM-generated, not officially verified)",
        "routing_total": routing_total,
        "routing_correct": routing_correct,
        "routing_accuracy": routing_correct / routing_total if routing_total else 0,
        "retrieval_total": retrieval_total,
        "retrieval_hit_rate": retrieval_hits / retrieval_total if retrieval_total else 0,
        "retrieval_recall_avg": sum(retrieval_recalls) / len(retrieval_recalls) if retrieval_recalls else 0,
        "errors": errors,
    }

    eval_dir = Path("data/eval_runs")
    eval_dir.mkdir(parents=True, exist_ok=True)
    timestamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    (eval_dir / f"labeled_eval_{timestamp}_metrics.json").write_text(json.dumps(metrics, indent=4))
    pd.DataFrame(rows).to_csv(eval_dir / f"labeled_eval_{timestamp}_details.csv", index=False)

    from services.rag_results import record_run
    record_run(
        eval_type="agent_eval_reasoning_only" if strip_flag else "agent_eval",
        metrics=metrics, details=rows, reranker_enabled=True,
    )

    return metrics, rows


def main():
    parser = argparse.ArgumentParser(description="Evaluate routing accuracy (vs. official escalation_flag) and retrieval quality (vs. LLM-generated labels).")
    parser.add_argument("--limit", type=int, default=30, help="Number of tickets to evaluate from train_index.csv (0 = all 256).")
    parser.add_argument("--sleep", type=float, default=0.0, help="Seconds to sleep between tickets (rate limiting).")
    parser.add_argument("--strip-flag", action="store_true",
                        help="Withhold escalation_flag from the agent to measure independent reasoning (harder; always-L1 baseline is 74.2%%).")
    args = parser.parse_args()

    metrics, _ = evaluate(limit=args.limit, sleep_between=args.sleep, strip_flag=args.strip_flag)
    print(json.dumps(metrics, indent=2))


if __name__ == "__main__":
    main()
